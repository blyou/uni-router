import { readFile } from 'node:fs/promises'
import type { PagesConfig } from '@uni-helper/uni-pages-types'
import type { RouteFileInfo, UniRouteInfo } from './types'
import { writeFileAtomic } from './utils'

function tabPaths(config: PagesConfig) {
  return new Set((config.tabBar?.list ?? []).map(item => item.pagePath.replace(/^\/+/, '')))
}

export function runtimeRoutes(routes: RouteFileInfo[], config: PagesConfig): UniRouteInfo[] {
  const tabs = tabPaths(config)
  return routes.map(route => ({
    path: `/${route.path}`,
    meta: route.meta,
    query: route.query,
    tab: tabs.has(route.path),
    ...(route.subPackage ? { subPackage: route.subPackage } : {}),
  }))
}

function queryType(route: RouteFileInfo) {
  const entries = Object.entries(route.query)
  if (!entries.length) return 'Record<string, never>'
  return `{\n${entries
    .map(([name, field]) => {
      const declared =
        route.queryTypes && Object.hasOwn(route.queryTypes, name)
          ? route.queryTypes[name]
          : undefined
      const type = declared ?? (field.type === 'object' ? 'Record<string, unknown>' : field.type)
      return `        ${JSON.stringify(name)}${field.required ? '' : '?'}: ${type}`
    })
    .join('\n')}\n      }`
}

export function generateDeclarations(routes: RouteFileInfo[], config: PagesConfig) {
  const runtime = runtimeRoutes(routes, config)
  const records = runtime.map((route, index) => {
    const source = routes[index]
    return [
      `    ${JSON.stringify(route.path)}: {`,
      `      query: ${queryType(source)}`,
      `      meta: PageMeta`,
      `      file: ${JSON.stringify(source.file)}`,
      `      tab: ${route.tab}`,
      '    }',
    ].join('\n')
  })

  return `/* eslint-disable */
/* oxlint-disable */
// @ts-nocheck
// biome-ignore-all lint: generated file
// dprint-ignore-file
// Generated by @blyou/uni-router. Do not edit.
/// <reference types="@blyou/uni-router/client" />

import type { PageMeta } from '@blyou/uni-router'
import '@blyou/uni-router'

/* prettier-ignore */
declare module '@blyou/uni-router' {
  interface UniRouteMap {
${records.join('\n')}
  }
}

export {}
`
}

export function generateVirtualModule(routes: RouteFileInfo[], config: PagesConfig) {
  const manifest = JSON.stringify(runtimeRoutes(routes, config))
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')
  return `export const routes = Object.freeze(JSON.parse(${JSON.stringify(manifest)}))\n`
}

export async function writeDeclarations(file: string, content: string) {
  let previous: string | undefined
  try {
    previous = await readFile(file, 'utf8')
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error
  }
  if (previous === content) return false
  await writeFileAtomic(file, content)
  return true
}
